import psycopg2
from psycopg2.extras import RealDictCursor

from helpers.environment import (
    CAMINHO_JSON_INSTITUICOES,
    CAMINHO_JSON_USUARIOS,
    DB_HOST,
    DB_NAME,
    DB_PASSWORD,
    DB_PORT,
    DB_USER,
)
from helpers.logger import logger
from helpers.storage import carregar_json

SCHEMA = """
CREATE TABLE IF NOT EXISTS instituicoes (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_entidade   TEXT NOT NULL,
    co_entidade   INTEGER NOT NULL,
    no_uf         TEXT,
    sg_uf         TEXT,
    co_uf         INTEGER,
    no_municipio  TEXT,
    co_municipio  INTEGER,
    nu_ano_censo  INTEGER,
    qt_mat_bas    INTEGER,
    qt_mat_inf    INTEGER,
    qt_mat_fund   INTEGER,
    qt_mat_med    INTEGER,
    qt_mat_prof   INTEGER,
    qt_mat_eja    INTEGER,
    qt_mat_esp    INTEGER,
    ativo         INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS usuarios (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          TEXT NOT NULL,
    email         TEXT NOT NULL,
    perfil        TEXT,
    ativo_usuario INTEGER NOT NULL DEFAULT 1,
    ativo         INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_instituicoes_co_entidade ON instituicoes (co_entidade, ativo);
CREATE INDEX IF NOT EXISTS idx_instituicoes_listagem ON instituicoes (ativo, co_entidade);
CREATE INDEX IF NOT EXISTS idx_instituicoes_sg_uf ON instituicoes (sg_uf);
CREATE INDEX IF NOT EXISTS idx_usuarios_email ON usuarios (email, ativo);
CREATE INDEX IF NOT EXISTS idx_usuarios_listagem ON usuarios (ativo, id);
"""

CAMPOS_INSTITUICAO = (
    "no_entidade",
    "no_uf",
    "sg_uf",
    "co_uf",
    "no_municipio",
    "co_municipio",
    "no_mesorregiao",
    "co_mesorregiao",
    "no_microrregiao",
    "co_microrregiao",
    "nu_ano_censo",
    "no_regiao",
    "co_regiao",
    "qt_mat_bas",
    "qt_mat_inf",
    "qt_mat_fund",
    "qt_mat_med",
    "qt_mat_prof",
    "qt_mat_eja",
    "qt_mat_esp",
)


# Evita que duas instâncias da API façam a carga inicial ao mesmo tempo
LOCK_INICIALIZACAO = 20262


def obter_conexao():
    """Retorna uma nova conexão PostgreSQL com linhas acessíveis por nome de coluna"""
    return psycopg2.connect(
        host=DB_HOST,
        port=DB_PORT,
        dbname=DB_NAME,
        user=DB_USER,
        password=DB_PASSWORD,
        connect_timeout=5,
        cursor_factory=RealDictCursor,
    )


def colunas_da_tabela(cursor, tabela):
    cursor.execute(
        "SELECT column_name FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = %s",
        (tabela,),
    )
    return {linha["column_name"] for linha in cursor.fetchall()}


def _tabela_vazia(cursor, tabela):
    cursor.execute(f"SELECT NOT EXISTS (SELECT 1 FROM {tabela}) AS vazia")
    return cursor.fetchone()["vazia"]


def _popular_instituicoes(cursor):
    if not _tabela_vazia(cursor, "instituicoes"):
        return
    existentes = colunas_da_tabela(cursor, "instituicoes")
    colunas = ("co_entidade",) + tuple(c for c in CAMPOS_INSTITUICAO if c in existentes)
    registros = carregar_json(CAMINHO_JSON_INSTITUICOES)
    parametros = [tuple(ie.get(campo) for campo in colunas) for ie in registros]
    cursor.executemany(
        f"INSERT INTO instituicoes ({', '.join(colunas)}) "
        f"VALUES ({', '.join(['%s'] * len(colunas))})",
        parametros,
    )
    logger.info(
        "Carga inicial: %d instituições inseridas em 'instituicoes'", len(parametros)
    )


def _popular_usuarios(cursor):
    if not _tabela_vazia(cursor, "usuarios"):
        return
    registros = carregar_json(CAMINHO_JSON_USUARIOS)
    parametros = [
        (
            usuario["id"],
            usuario.get("nome"),
            usuario.get("email"),
            usuario.get("perfil"),
            1 if usuario.get("ativo", True) else 0,
        )
        for usuario in registros
    ]
    cursor.executemany(
        "INSERT INTO usuarios (id, nome, email, perfil, ativo_usuario) "
        "VALUES (%s, %s, %s, %s, %s)",
        parametros,
    )
    if parametros:
        # ids explícitos não avançam a sequência da coluna IDENTITY
        cursor.execute(
            "SELECT setval(pg_get_serial_sequence('usuarios', 'id'), MAX(id)) "
            "FROM usuarios"
        )
    logger.info("Carga inicial: %d usuários inseridos em 'usuarios'", len(parametros))


def inicializar_banco():
    """Cria tabelas e índices e, só se as tabelas estiverem vazias, carrega os JSON."""
    try:
        conexao = obter_conexao()
        try:
            with conexao, conexao.cursor() as cursor:
                cursor.execute(
                    "SELECT pg_advisory_xact_lock(%s)", (LOCK_INICIALIZACAO,)
                )
                cursor.execute(SCHEMA)
                _popular_instituicoes(cursor)
                _popular_usuarios(cursor)
        finally:
            conexao.close()
    except psycopg2.OperationalError:
        logger.error(
            "Banco de dados indisponível em %s:%s/%s. "
            "Verifique se o container do PostgreSQL está ativo e se o .env está correto.",
            DB_HOST,
            DB_PORT,
            DB_NAME,
        )
        raise
    except (OSError, psycopg2.Error, ValueError):
        logger.exception("Falha ao inicializar o banco de dados %s", DB_NAME)
        raise
    return DB_NAME
